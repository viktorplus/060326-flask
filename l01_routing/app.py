# Самый первый, «скелетный» пример Flask-приложения: маршрутизация и конвертеры путей.

# Импортируем класс Flask — это и есть WSGI-приложение, ядро фреймворка.
from flask import Flask

# Создаём экземпляр приложения.
# __name__ — имя текущего модуля; Flask использует его, чтобы понять,
# где лежит корень приложения (для поиска templates/, static/ и для отладки).
app = Flask(__name__)


# Декоратор @app.route регистрирует функцию как обработчик URL '/'.
# Правило (rule) кладётся в app.url_map; при запросе Flask ищет совпадение и вызывает функцию.
@app.route('/')
def index():  # put application's code here
    # Возврат строки = HTTP 200 с Content-Type: text/html и этим текстом в теле.
    return 'Index Page'
# Второй маршрут: статический путь без параметров.
@app.route('/menu')
def menu():
    return 'Menu Page'


# Динамическая часть пути в угловых скобках: <int:id>.
# 'int' — встроенный конвертер: он принимает ТОЛЬКО цифры и передаёт в функцию уже int, а не str.
# '/menu/abc' сюда не попадёт (конвертер не совпадёт).
@app.route('/menu/<int:id>')
def dish(id):  # имя аргумента функции обязано совпадать с именем в <...>
    # f-строка подставляет значение параметра в ответ.
    return f'Dish id is {id}'


# Конвертер 'any' ограничивает значение фиксированным списком вариантов.
# Сюда подойдут только '/status/pending' и '/status/active'.
@app.route('/status/<any(pending, active):status>')
def check_status(status):
    return f'Status is {status}'


# Два динамических сегмента подряд. Конвертер по умолчанию — 'string':
# принимает любой текст БЕЗ слеша, поэтому '/a/b' совпадёт, а '/a/b/c' — нет.
@app.route('/<category>/<sub>')
def dish_cat(category, sub):
    # Аргументы приходят в функцию как именованные, порядок в сигнатуре неважен.
    return f'Dish category is: {category} and sub is {sub}'




# ВНИМАНИЕ (учебный момент): правило '/<name>' конкурирует с '/menu' —
# по форме под него подходит любой одиночный сегмент пути.
# Flask сортирует правила по «специфичности», а не по порядку объявления,
# поэтому статический '/menu' выигрывает у динамического '/<name>'.
# Сюда попадут только те одиночные сегменты, для которых нет точного маршрута.


@app.route('/<name>')
def hello_name(name):
    # Конкатенация строк вместо f-строки — работает так же, просто менее читаемо.
    return 'Hello, ' + name + '!'


# Блок запускается, только если файл выполнен напрямую (python app.py),
# и НЕ выполняется при импорте модуля — стандартная защита точки входа.
if __name__ == '__main__':
    # Поднимает встроенный отладочный сервер на http://127.0.0.1:5000.
    # Для продакшена не годится — там нужен WSGI-сервер (gunicorn/uwsgi).
    app.run()
